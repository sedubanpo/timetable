const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
const flush = async () => { for (let i = 0; i < 30; i++) await Promise.resolve(); };
async function check(file) {
  const html = fs.readFileSync(path.join(root, file), 'utf8');
  const app = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m => m[1]).filter(s => s.trim()).pop();
  const scope = {console, window: {addEventListener() {}}, document: {addEventListener() {}, getElementById() {return {style: {}, classList: {add() {}, remove() {}}};}, querySelectorAll: () => []}, localStorage: {getItem: () => null}, setTimeout() {}, clearTimeout() {}, setInterval() {}, clearInterval() {}, URLSearchParams, Date, Promise, Set, Map};
  vm.createContext(scope);
  vm.runInContext(app, scope);
  const run = code => vm.runInContext(code, scope);
  run(`authState={loggedIn:true,loginId:'a'}; globalThis.auth={currentUser:{uid:'a',getIdToken:()=>Promise.resolve('a')}};
    getLiveFirebaseAuth=()=>Promise.resolve(auth);globalThis.requests=[];
    globalThis.originalFetchEnrollment=fetchEnrollmentStatusStudents;
    fetchEnrollmentStatusStudents=()=>new Promise((resolve,reject)=>requests.push({resolve,reject}));`);
  const rows = [{id:'1',name:'Alice',school:'School 1',active:true},{id:'old',name:'Alice',status:'WITHDRAWN'},{id:'2',name:'Bob',status:'ON_HOLD'}];
  async function refresh(data, expected, force = true) {
    const p = run(`loadStudentEnrollmentStatusWarnings(${force})`);
    await flush(); scope.rows = data; run('requests.at(-1).resolve(rows)');
    assert.equal(await p, expected);
  }
  const first = run('loadStudentEnrollmentStatusWarnings()');
  const shared = run('loadStudentEnrollmentStatusWarnings(true)');
  await flush(); assert.equal(run('requests.length'), 1, 'same-context inflight shared');
  scope.rows = rows; run('requests[0].resolve(rows)');
  assert.equal(await first, true); assert.equal(await shared, true);
  assert.equal(run(`getEnrollmentWarningForStudent('Alice')`), '', 'historical withdrawal cannot override active record');
  assert.equal(run(`getEnrollmentIdentityForStudent('Alice','School 1').studentId`), '1');
  assert.equal(await run('loadStudentEnrollmentStatusWarnings()'), false);
  assert.equal(run('requests.length'), 1, 'five-minute freshness skips network');
  await refresh([...rows].reverse().map(r => ({...r, irrelevant: 'metadata'})), false);
  assert.equal(run('requests.length'), 2, 'force bypasses fresh cache');
  run('studentEnrollmentStatusState.loadedAt=Date.now()-300001');
  await refresh(rows, false, false);
  const changedStatus = rows.map(r => r.name === 'Bob' ? {...r,status:'WITHDRAWN'} : r);
  await refresh(changedStatus, true);
  const changedSchool = changedStatus.map(r => r.id === '1' ? {...r,school:'School 2'} : r);
  await refresh(changedSchool, true);
  const changedId = changedSchool.map(r => r.id === '1' ? {...r,id:'new'} : r);
  await refresh(changedId, true);
  assert.equal(run(`getEnrollmentIdentityForStudent('Alice','School 2').studentId`), 'new');
  await refresh(changedId.map(r => r.id === 'new' ? {...r,active:false} : r), true);
  assert.equal(run(`getEnrollmentIdentityForStudent('Alice','School 2')`), null);
  const failed = run('loadStudentEnrollmentStatusWarnings(true)');
  await flush(); run(`requests.at(-1).reject(new Error('offline'))`);
  await assert.rejects(failed, /offline/);
  assert.equal(run('studentEnrollmentStatusState.warningCount'), 3, 'same-context failure preserves known data');
  assert.equal(run('studentEnrollmentStatusState.loading'), null);
  const old = run('loadStudentEnrollmentStatusWarnings(true)');
  await flush(); run('globalThis.oldRequest=requests.at(-1)');
  // Exercise the real logout reset prefix without unrelated UI teardown dependencies.
  const logoutPrefix = app.slice(app.indexOf('function logoutTeacher() {'), app.indexOf('        studentCardStatusSequence++;', app.indexOf('function logoutTeacher() {')));
  vm.runInContext(logoutPrefix.replace('function logoutTeacher() {', '') , scope);
  run(`authState={loggedIn:true,loginId:'b'};auth.currentUser={uid:'b',getIdToken:()=>Promise.resolve('b')}`);
  const newer = run('loadStudentEnrollmentStatusWarnings(true)');
  await flush(); run('globalThis.newRequest=requests.at(-1);oldRequest.resolve([{id:"stale",name:"Stale"}])');
  assert.equal(await old, false);
  assert(run('studentEnrollmentStatusState.loading !== null'), 'old cleanup cannot clear new inflight');
  assert.equal(run('Object.keys(studentEnrollmentStatusState.identitiesByName).length'), 0);
  run('newRequest.resolve([{id:"b",name:"B"}])');assert.equal(await newer,true);
  const accountOld = run('loadStudentEnrollmentStatusWarnings(true)');
  await flush();run('globalThis.accountOldRequest=requests.at(-1);auth.currentUser={uid:"c",getIdToken:()=>Promise.resolve("c")}');
  const accountNew = run('loadStudentEnrollmentStatusWarnings(true)');
  await flush();run('accountOldRequest.reject(new Error("stale failure"))');
  assert.equal(await accountOld,false);
  assert.equal(run('studentEnrollmentStatusState.error'), '');
  run('requests.at(-1).reject(new Error("new failure"))');
  await assert.rejects(accountNew,/new failure/);
  assert.equal(run('Object.keys(studentEnrollmentStatusState.identitiesByName).length'),0,'failed new identity cannot retain old identity data');
  const loginOld = run('loadStudentEnrollmentStatusWarnings(true)');
  await flush(); run('globalThis.loginOldRequest=requests.at(-1);authState.loginId="different-login"');
  const loginNew = run('loadStudentEnrollmentStatusWarnings(true)');
  await flush(); run('loginOldRequest.resolve([{id:"wrong",name:"Wrong"}])');
  assert.equal(await loginOld,false,'application account change invalidates even with same Firebase user');
  run('requests.at(-1).resolve([{id:"right",name:"Right"}])'); assert.equal(await loginNew,true);
  const logoutPending = run('loadStudentEnrollmentStatusWarnings(true)');
  await flush(); run('resetStudentEnrollmentStatus();requests.at(-1).resolve([{id:"late",name:"Late"}])');
  assert.equal(await logoutPending,false);
  assert.equal(run('Object.keys(studentEnrollmentStatusState.identitiesByName).length'),0,'logout alone cannot be refilled');
  // Logout while Firebase initialization is unresolved must not start a fetch.
  run('getLiveFirebaseAuth=()=>new Promise(resolve=>globalThis.authResolve=resolve)');
  const before = run('requests.length');
  const pendingAuth = run('loadStudentEnrollmentStatusWarnings(true)');
  run('resetStudentEnrollmentStatus();authResolve(auth)');
  assert.equal(await pendingAuth,false); assert.equal(run('requests.length'),before);
  // Exercise production pagination beyond old historical limits.
  run(`globalThis.page=0;fetch=()=>Promise.resolve({ok:true,json:()=>Promise.resolve({documents:Array.from({length:300},(_,i)=>({name:'students/'+(page*300+i),fields:{name:{stringValue:'Name'+(page*300+i)}}})),nextPageToken:++page<6?'next':''})});`);
  assert.equal((await run('originalFetchEnrollment("token")')).length,1800);
  console.log(file + ': enrollment semantics, freshness/force, identities, session races, failure isolation and 1800-row pagination passed');
}
(async()=>{await check('Index.html');await check('docs/index.html');})().catch(error=>{console.error(error);process.exitCode=1;});
